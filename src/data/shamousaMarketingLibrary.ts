export interface MarketingPostTemplate {
  id: string;
  typeAr: string;
  template: string;
  note?: string;
}

export interface MarketingObjectionReply {
  id: string;
  objectionAr: string;
  triggers: string[];
  guidanceAr: string;
}

export interface MarketingSeasonEntry {
  id: string;
  seasonAr: string;
  keywords: string[];
  suitableProductsAr: string;
}

export interface MarketingGeneralSection {
  titleTemplates: string[];
  hooks: string[];
  descriptionStructures: Array<{ id: string; labelAr: string; structureAr: string }>;
  postTemplates: MarketingPostTemplate[];
  ctas: string[];
  engagementQuestions: string[];
  shortVideoIdeas: string[];
  generalPhotoTips: string;
  objectionReplies: MarketingObjectionReply[];
  whatsappTemplates: {
    welcome: {
      fast: string;
      friendly: string;
      formal: string;
    };
    productOffer: {
      fast: string;
      friendly: string;
      formal: string;
    };
    followUp: string;
    afterDelivery: string;
    afterDeliveryNote: string;
  };
  seasonsAndOccasions: MarketingSeasonEntry[];
}

export interface CraftMarketingFaq {
  questionAr: string;
  answerGuidanceAr: string;
}

export interface CraftMarketingSpecialty {
  /** معرّف فريد للتخصص (إضافة أي تخصص جديد هنا تعمل تلقائياً في المحرك بدون تعديل الكود) */
  id: string;
  /** اسم التخصص بالعربية */
  nameAr: string;
  /** الدفعة التابع لها */
  batch: number;
  /** كلمات دالة للتعرف على التخصص من كلام المستخدم */
  keywords: string[];
  /** رائج (تقديري — بيانات مبيعات الحساب الفعلية تتقدم عليه) */
  popularItems: string[];
  /** نقط بيع */
  sellingPoints: string[];
  /** باقات مقترحة */
  bundles: string[];
  /** خامات نموذجية (تُربط بالخامات الموحدة بأسمائها) */
  typicalMaterials: string[];
  /** مناسبات */
  occasions: string[];
  /** نصايح تصوير خاصة بالتخصص */
  photoTips: string;
  /** ممنوعات خاصة بالتخصص (إن وُجدت) */
  forbiddenClaimsAr?: string;
  /** فكرة خاصة بالتخصص (مثل دمج الحِرف) */
  ideaAr?: string;
  /** ملحوظة خاصة بالتخصص (مثل ربط ورشة دمج الحِرف في الحاسبة) */
  noteAr?: string;
  /** أسئلة العملاء الشائعة وإرشاد الرد عليها */
  customerFaqs: CraftMarketingFaq[];
  /** أفكار فيديو خاصة بالتخصص */
  videoIdeas: string[];
  /** وسوم / هاشتاجات */
  hashtags: string[];
}

export interface SuppliersMarketingSection {
  nameAr: string;
  typesAr: string[];
  sellingPointsForWorkshops: string[];
  starterKits: Array<{ titleAr: string; contentsAr: string }>;
  seasonsAr: string;
  postTemplates: string[];
  workshopMessageTemplate: string;
  customerFaqs: CraftMarketingFaq[];
  hashtags: string[];
}

