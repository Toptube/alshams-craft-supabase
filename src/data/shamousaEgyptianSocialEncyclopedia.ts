const REAL_TASK_OR_PRODUCT_CUE_RE =
  /(هديه|شنطه|مكرميه|ريزن|شموع|خيط|سعر|بكام|كام\s*سعر|تكلفه|تكاليف|تسويق|سوق|باقه|باقات|مخزن|فاتوره|خزنه|مورد|خامات|حاسبه|اصول|طباعه|نسخ\s*احتياطي|ميزان|قفل\s*الشهر|شحن|خصم|نقاط|دعوه|مقارنه|مفضله|هلخصهالك|كاشير|فروع|سجل\s*التحديث|جيسمونايت|كونكريت|ليزر|3d|ثلاثيه\s*الابعاد|ازاي\s*اعمل|ازاي\s*اسعر|ازاي\s*اطبع|عندكم\s*ايه|عايز\s*اسعر|راجع\s*منتجاتي|اكتب\s*لي\s*بوست|دليل\s*الاستخدام|قاموس|كارت\s*الصنف|امر\s*تشغيل|سلف|رواتب|منتج\s*جديد|عروض|طيران|فنادق|جبنه|سوداني)/;

const RHETORICAL_ADMIRATION_QUESTION_RE =
  /(ايه\s*(الجمال|الحلاوه|الشياكه|العظمه|الروعه|الابداع|الذوق|الذكاء|الطعامه)\s*(ده|دي))/;

const SOCIAL_GREETING_QUESTION_RE =
  /(عامله\s*ايه|عامل\s*ايه|اخبارك\s*ايه|ايه\s*الاخبار|ازيك|انتي?\s*هنا|موجوده|عندك\s*مايوه|بتطبخي|سنك\s*كام|عندك\s*كام\s*سنه|بتنامي\s*امتي|اخبار\s*الطقس|الجو\s*ايه|انتي?\s*متجوزه|هتتجوزيني|بتاكلي\s*ايه|الاهلي\s*ولا\s*الزمالك)/;

export interface EgyptianSocialMatchResult {
  category: EgyptianSocialCategory;
  titleAr: string;
  baseReply: string;
  score: number;
}

/**
 * المصنّف الذكي للموسوعة الاجتماعية المصرية:
 * يفحص العبارات الكاملة + الكلمات المفردة + تحمّل الأخطاء الإملائية + السياق (مثل ذكر صقر)
 * بدون قيود ^...$ جامدة، ومع حارس ذكي يمنع ابتلاع الأسئلة العملية الحقيقية.
 */
export function matchEgyptianSocialEncyclopedia(
  rawQuery: string,
  whoLabel: string,
  options?: { allowGreetings?: boolean; allowPlayful?: boolean; allowShortAck?: boolean }
): EgyptianSocialMatchResult | null {
  const norm = normalizeSocialArabicText(rawQuery);
  if (!norm) return null;

  const trimmed = rawQuery.trim();
  const tokens = norm.split(/\s+/).filter(Boolean);
  if (tokens.length === 0) return null;

  // لو الجملة طويلة جداً (> 18 كلمة) غالباً هي استفسار عملي وليست مجاملة قصيرة
  if (tokens.length > 18) return null;

  // حارس النية الحقيقية: لو الجملة فيها سؤال تقني/تجاري واضح أو علامة استفهام حقيقية (غير بلاغية) -> لا نبتلعها!
  const isRhetoricalOrSocialQuestion =
    RHETORICAL_ADMIRATION_QUESTION_RE.test(norm) || SOCIAL_GREETING_QUESTION_RE.test(norm);
  const hasRealTaskOrQuestion =
    REAL_TASK_OR_PRODUCT_CUE_RE.test(norm) ||
    ((trimmed.endsWith('؟') || trimmed.endsWith('?')) && !isRhetoricalOrSocialQuestion);

  if (hasRealTaskOrQuestion) return null;

  const allowGreetings = options?.allowGreetings ?? true;
  const allowPlayful = options?.allowPlayful ?? true;
  const allowShortAck = options?.allowShortAck ?? true;

  // تقييم كل أبواب الموسوعة واختيار الأعلى تطابقاً
  let best: { entry: SocialEncyclopediaEntry; score: number } | null = null;

  for (const entry of EGYPTIAN_SOCIAL_ENCYCLOPEDIA) {
    if (entry.category === 'greetings_warm' && !allowGreetings) continue;
    if (entry.category === 'playful_banter' && !allowPlayful) continue;
    if (entry.category === 'acknowledgment_agreement' && !allowShortAck) continue;

    let score = 0;

    // 1) مطابقة العبارات المتعددة الكلمات في أي موضع داخل الجملة
    for (const phrase of entry.phrases) {
      const np = normalizeSocialArabicText(phrase);
      if (np.length >= 3 && norm.includes(np)) {
        score += np.includes(' ') ? 20 : 14;
      }
    }

    // 2) مطابقة الكلمات المفردة + تحمّل الأخطاء الإملائية + إزالة واو/فاء العطف
    for (const rawTok of tokens) {
      const tk = stripOptionalPrefixes(rawTok);
      if (tk.length < 2) continue;

      for (const fw of entry.fuzzyWords) {
        const nfw = normalizeSocialArabicText(fw);
        if (tk === nfw) {
          score += 14;
          break;
        }
        if (tk.length >= 4 && nfw.length >= 4) {
          if (tk.startsWith(nfw) && tk.length - nfw.length <= 2) {
            score += 12;
            break;
          }
          if (socialLevenshtein(tk, nfw) <= 1) {
            score += 10;
            break;
          }
        }
      }
    }

    // عبارات الموافقة القصيرة ("تمام"، "ماشي"، "أوكي") تُقبل فقط في الجمل القصيرة (<= 5 كلمات)
    if (entry.category === 'acknowledgment_agreement') {
      if (tokens.length > 5) continue;
      if (/^(تمام|ماشي|اوك|حاضر|اكيد|طبعا|صح|جميل|حلو|عظيم)$/.test(norm)) {
        score += 14;
      }
    }

    // التحية بكلمة واحدة ("سلام" / "هاي" / "الو" / "شموسة")
    if (entry.category === 'greetings_warm' && /^(هاي|هلا|الو|شموسه|يا\s*شموسه)$/.test(norm)) {
      score += 16;
    }
    if (entry.category === 'farewell_polite' && /^سلام$/.test(norm)) {
      score += 16;
    }

    if (score > 0 && (!best || score > best.score)) {
      best = { entry, score };
    }
  }

  if (!best || best.score < 10) return null;

  // حالة خاصة مميزة: لو الجملة فيها دعوة أو مجاملة أو شكر مع ذكر «أخوك / صقر / أنتم الاتنين»
  const isWarmCategory =
    best.entry.category === 'blessing_prayer' ||
    best.entry.category === 'gratitude' ||
    best.entry.category === 'admiration_work_quality' ||
    best.entry.category === 'personal_compliment_shamousa';

  if (isWarmCategory && SAQR_OR_BROTHER_MENTION_RE.test(norm)) {
    const saqrReply = pickSocialVariant(norm, [
      `تسلم ${whoLabel}، دعوة جميلة أعتز بيها والله! ☀️🦅 ربنا يبارك في حضرتك ويوفقك دايماً — أنا وأخويا **صقر** تحت أمرك في أي وقت.`,
      `كلك ذوق ${whoLabel}، ولك بالمثل وأجمل كمان! ☀️🦅 دعوة راقية تسعدني أنا وأخويا **صقر**، ودايماً معاك بأعلى مستوى.`,
    ]);
    return {
      category: 'blessing_with_saqr',
      titleAr: 'دعوة ومجاملة لشموسة وصقر',
      baseReply: saqrReply,
      score: best.score + 10,
    };
  }

  const chosenReplyFn = pickSocialVariant(norm, best.entry.replies);
  return {
    category: best.entry.category,
    titleAr: best.entry.titleAr,
    baseReply: chosenReplyFn(whoLabel),
    score: best.score,
  };
}
