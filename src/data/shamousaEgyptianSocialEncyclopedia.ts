export function normalizeSocialArabicText(raw: string): string {
  // إزالة أي حرف سيريلي/غريب شارد وسط الكلمة العربية (مثل: يحмиيك -> يحميك)
  const strippedStrayForeign = raw.replace(/([\u0600-\u06FF])[\u0400-\u04FF]+([\u0600-\u06FF])/g, '$1$2');
  let norm = normalizeArabicKnowledgeText(strippedStrayForeign);
  // ضغط تكرار 3 أحرف فأكثر إلى حرف واحد (تحفههه -> تحفه، بجددد -> بجد)
  norm = norm.replace(/(.)\1{2,}/g, '$1');
  // ضغط تكرار حروف المد والهاء المطبعي الشائع في الشات المصري (يحمييك -> يحميك، هايلله -> هايله، تسلميي -> تسلمي)
  norm = norm
    .replace(/يي/g, 'ي')
    .replace(/وو/g, 'و')
    .replace(/اا/g, 'ا')
    .replace(/هه/g, 'ه');
  return norm.trim();
}

export function socialLevenshtein(a: string, b: string): number {
  if (a === b) return 0;
  if (!a.length) return b.length;
  if (!b.length) return a.length;
  if (Math.abs(a.length - b.length) > 2) return 3;

  const dp: number[] = Array.from({ length: b.length + 1 }, (_, j) => j);
  for (let i = 1; i <= a.length; i++) {
    let prev = dp[0];
    dp[0] = i;
    for (let j = 1; j <= b.length; j++) {
      const temp = dp[j];
      const cost = a[i - 1] === b[j - 1] ? 0 : 1;
      dp[j] = Math.min(dp[j] + 1, dp[j - 1] + 1, prev + cost);
      prev = temp;
    }
  }
  return dp[b.length];
}

function stripOptionalPrefixes(token: string): string {
  // يشيل واو/فاء العطف الشائعة زي وبشكرك -> بشكرك، وتسلميلي -> تسلميلي
  if (token.length >= 5 && /^[وف]/.test(token)) {
    return token.slice(1);
  }
  return token;
}

export function pickSocialVariant<T>(seed: string, list: T[]): T {
  let hash = 0;
  for (let i = 0; i < seed.length; i++) {
    hash = (hash * 31 + seed.charCodeAt(i)) >>> 0;
  }
  return list[hash % list.length];
}

