// حارس النية الحقيقية: لو التحية مدموجة بسؤال عملي حقيقي (مثلاً: "السلام عليكم، الباقات بكام؟") لا نبتلع السؤال!
const REAL_TASK_OR_PRODUCT_CUE_RE =
  /(هديه|شنطه|مكرميه|ريزن|شموع|خيط|سعر|بكام|كام\s*سعر|تكلفه|تكاليف|تسويق|سوق|باقه|باقات|مخزن|فاتوره|خزنه|مورد|خامات|حاسبه|اصول|طباعه|نسخ\s*احتياطي|ميزان|قفل\s*الشهر|شحن|خصم|نقاط|دعوه|مقارنه|مفضله|هلخصهالك|كاشير|فروع|سجل\s*التحديث|جيسمونايت|كونكريت|ليزر|3d|ثلاثيه\s*الابعاد|ازاي\s*اعمل|ازاي\s*اسعر|ازاي\s*اطبع|عندكم\s*ايه|عايز\s*اسعر|راجع\s*منتجاتي|اكتب\s*لي\s*بوست|دليل\s*الاستخدام|قاموس|كارت\s*الصنف|امر\s*تشغيل|سلف|رواتب|منتج\s*جديد|عروض|طيران|فنادق|جبنه|سوداني|صمم|مصمم|مؤسس|حسام\s*بسيوني|تايجوس|الشمس\s*كرافت|قائمه|القائمه|مساعده|رجوع|بتعملي\s*ايه)/;

const GREETING_QUESTION_ALLOWED_RE =
  /(عامله\s*ايه|عامل\s*ايه|عاملين\s*ايه|اخبارك\s*ايه|ايه\s*الاخبار|ايه\s*اخبارك|ازيك|كيف\s*حالك|كيف\s*الحال|كيفك|شلونك|شخبارك|احوالك\s*ايه|انتي?\s*هنا|موجوده|صاحيه|كله\s*تمام|how\s*are\s*you|whats\s*up)/;

function stripPrefix(token: string): string {
  if (token.length >= 5 && /^[وف]/.test(token)) {
    return token.slice(1);
  }
  return token;
}

/**
 * المصنّف الذكي لموسوعة السلام والترحيب والوداع:
 * يميّز بدقة بين تحية الإسلام (السلام عليكم) وسلام الوداع (سلام / سلام يا قمر)،
 * ويختار الرد الأصيل المخصص لاسم المستخدم ومكانه في المنظومة.
 */
export function matchGreetingsAndFarewellsEncyclopedia(
  rawQuery: string,
  surface: GreetingFarewellSurfaceInfo
): GreetingFarewellMatchResult | null {
  const norm = normalizeSocialArabicText(rawQuery);
  if (!norm) return null;

  const trimmed = rawQuery.trim();
  const tokens = norm.split(/\s+/).filter(Boolean);
  if (tokens.length === 0 || tokens.length > 14) return null;

  // حارس النية الحقيقية: لا نبتلع أي سؤال تقني أو تجاري مدموج مع التحية
  const isGreetingQuestion = GREETING_QUESTION_ALLOWED_RE.test(norm);
  if (
    REAL_TASK_OR_PRODUCT_CUE_RE.test(norm) ||
    ((trimmed.endsWith('؟') || trimmed.endsWith('?')) && !isGreetingQuestion)
  ) {
    return null;
  }

  let best: { entry: GreetingFarewellEntry; score: number } | null = null;

  for (const entry of GREETINGS_FAREWELLS_ENCYCLOPEDIA) {
    let score = 0;

    // 1) مطابقة العبارات في أي موضع داخل الجملة
    for (const phrase of entry.phrases) {
      const np = normalizeSocialArabicText(phrase);
      if (np.length >= 3 && norm.includes(np)) {
        // أولوية أعلى للعبارات المركبة الأطول (مثل "السلام عليكم" أو "سلام يا قمر" أو "صباح الفل يا قمر")
        score += np.includes(' ') ? 24 + Math.min(np.length, 16) * 0.4 : 16;
      }
    }

    // 2) الكلمات القصيرة الدقيقة في الرسائل القصيرة جداً (<= 3 كلمات، مثل "سلام" أو "باي" أو "هاي")
    if (entry.shortOnlyExact && tokens.length <= 3) {
      for (const exactWord of entry.shortOnlyExact) {
        const nw = normalizeSocialArabicText(exactWord);
        if (norm === nw) {
          score += 24;
        } else if (tokens.includes(nw)) {
          // تجنب خلط "سلام" مع "السلام عليكم" / "سلام عليكم"
          if (nw === 'سلام' && /(عليكم|عليكو)/.test(norm)) continue;
          score += 18;
        }
      }
    }

    // 3) الكلمات المفردة + تحمّل الأخطاء الإملائية
    for (const rawTok of tokens) {
      const tk = stripPrefix(rawTok);
      if (tk.length < 3) continue;
      for (const fw of entry.fuzzyWords) {
        const nfw = normalizeSocialArabicText(fw);
        if (tk === nfw) {
          score += 16;
          break;
        }
        if (tk.length >= 4 && nfw.length >= 4 && socialLevenshtein(tk, nfw) <= 1) {
          score += 12;
          break;
        }
      }
    }

    // حسم التعارض بين "سلام عليكم" (تحية) و"سلام" (وداع)
    if (entry.category === 'farewell_salam_sweet' && /(السلام\s*عليك|سلام\s*عليك|سلامو\s*عليك)/.test(norm)) {
      score = 0;
    }

    if (score > 0 && (!best || score > best.score)) {
      best = { entry, score };
    }
  }

  if (!best || best.score < 12) return null;

  return {
    category: best.entry.category,
    group: best.entry.group,
    titleAr: best.entry.titleAr,
    reply: best.entry.buildReply(surface, norm),
    score: best.score,
  };
}
