const STORAGE_QUICK_LANGS_KEY = 'alshams_quick_languages';

export function getStoredLanguage(): LanguageCode {
  try {
    const saved = localStorage.getItem(STORAGE_LANG_KEY);
    if (saved && SUPPORTED_LANGUAGES.some((l) => l.code === saved)) {
      return saved as LanguageCode;
    }
  } catch (e) {}
  return 'ar';
}

export function setStoredLanguage(lang: LanguageCode): void {
  try {
    localStorage.setItem(STORAGE_LANG_KEY, lang);
    const langInfo = SUPPORTED_LANGUAGES.find((l) => l.code === lang);
    if (langInfo) {
      document.documentElement.dir = langInfo.dir;
      document.documentElement.lang = langInfo.code;
    }
    window.dispatchEvent(new CustomEvent('alshams_language_changed', { detail: { lang } }));
  } catch (e) {}
}

export function getStoredQuickLanguages(): LanguageCode[] {
  try {
    const saved = localStorage.getItem(STORAGE_QUICK_LANGS_KEY);
    if (saved) {
      const parsed = JSON.parse(saved);
      if (Array.isArray(parsed) && parsed.length >= 2) {
        return parsed.slice(0, 3) as LanguageCode[];
      }
    }
  } catch (e) {}
  return DEFAULT_QUICK_SWITCH_LANGUAGES;
}

export function setStoredQuickLanguages(langs: LanguageCode[]): void {
  try {
    const valid = langs.filter((code) => SUPPORTED_LANGUAGES.some((l) => l.code === code)).slice(0, 3);
    localStorage.setItem(STORAGE_QUICK_LANGS_KEY, JSON.stringify(valid));
    window.dispatchEvent(new CustomEvent('alshams_quick_languages_changed', { detail: { langs: valid } }));
  } catch (e) {}
}

export function t(key: string, lang?: LanguageCode): string {
  const currentLang = lang || getStoredLanguage();
  const dict = TRANSLATIONS[currentLang] || TRANSLATIONS.ar;
  return dict[key] || TRANSLATIONS.ar[key] || key;
}

// React hook for reactive multilingual updates across components
export function useTranslation() {
  const [lang, setLang] = useState<LanguageCode>(getStoredLanguage());

  useEffect(() => {
    const handleLangChange = (e: any) => {
      const newLang = (e.detail?.lang || getStoredLanguage()) as LanguageCode;
      setLang(newLang);
    };
    window.addEventListener('alshams_language_changed', handleLangChange);
    return () => window.removeEventListener('alshams_language_changed', handleLangChange);
  }, []);

  const langInfo = SUPPORTED_LANGUAGES.find((l) => l.code === lang) || SUPPORTED_LANGUAGES[0];

  return {
    lang,
    dir: langInfo.dir,
    langInfo,
    t: (key: string) => t(key, lang),
    setLanguage: setStoredLanguage,
  };
}
